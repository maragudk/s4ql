// lalr is the LALR(1) automaton that Lemon generated from parse.y, as its tables are in the vendored
// amalgamation, driven as the template lempar.c drives it. It is a test instrument, never used by
// the parser: run over the tokens that the parser hands on, it tells which rules of parse.y SQLite's
// own parser reduces for a statement, which gives the rule coverage of the tests, how deep its stack
// grows, which bounds the depth limit of the parser, and at which token it fails, which checks the
// parser once more.
type lalr struct {
	action, lookahead, shiftOfst, reduceOfst, dflt, fallback, ruleLHS, ruleNRHS []int
	c                                                                           map[string]int
	// tk is the code of each token by the name of its TK_ macro without the prefix.
	tk map[string]int
}

var (
	lalrOnce sync.Once
	theLALR  *lalr
	lalrErr  error
)

func loadLALR(t testing.TB) *lalr {
	t.Helper()
	lalrOnce.Do(func() {
		b, err := os.ReadFile("../../sqlite/c/sqlite3.c")
		if err != nil {
			lalrErr = err
			return
		}
		theLALR, lalrErr = parseTables(string(b))
	})
	if lalrErr != nil {
		t.Fatal(lalrErr)
	}
	return theLALR
}

var (
	cComment = regexp.MustCompile(`(?s)/\*.*?\*/`)
	cDefine  = regexp.MustCompile(`(?m)^#define (YY\w+|TK_\w+)\s+\(?(-?\d+)\)?\s*$`)
)

// parseTables of the parser in the amalgamation src: the arrays of the first parser in it, which is
// SQLite's, and the macros for its constants and token codes.
func parseTables(src string) (*lalr, error) {
	start := strings.Index(src, "/* This file is automatically generated by Lemon from input grammar")
	end := strings.Index(src, "SQLITE_PRIVATE int sqlite3ParserFallback(int iToken){")
	if start < 0 || end < 0 {
		return nil, fmt.Errorf("the parser is not in the amalgamation")
	}
	src = src[start:end]
	l := &lalr{c: map[string]int{}, tk: map[string]int{}}
	for _, m := range cDefine.FindAllStringSubmatch(src, -1) {
		n, _ := strconv.Atoi(m[2])
		if name, ok := strings.CutPrefix(m[1], "TK_"); ok {
			l.tk[name] = n
		} else {
			l.c[m[1]] = n
		}
	}
	arrays := map[string]*[]int{
		"yy_action": &l.action, "yy_lookahead": &l.lookahead, "yy_shift_ofst": &l.shiftOfst,
		"yy_reduce_ofst": &l.reduceOfst, "yy_default": &l.dflt, "yyFallback": &l.fallback,
		"yyRuleInfoLhs": &l.ruleLHS, "yyRuleInfoNRhs": &l.ruleNRHS,
	}
	for name, dst := range arrays {
		i := strings.Index(src, " "+name+"[] = {")
		if i < 0 {
			return nil, fmt.Errorf("no array %v", name)
		}
		body := src[i+strings.Index(src[i:], "{")+1:]
		body = body[:strings.Index(body, "};")]
		body = cComment.ReplaceAllString(body, "")
		for _, f := range strings.Split(body, ",") {
			if f = strings.TrimSpace(f); f == "" {
				continue
			}
			n, err := strconv.Atoi(f)
			if err != nil {
				return nil, fmt.Errorf("%v: %w", name, err)
			}
			*dst = append(*dst, n)
		}
	}
	return l, nil
}

// findShift is yy_find_shift_action.
func (l *lalr) findShift(look, state int) int {
	if state > l.c["YY_MAX_SHIFT"] {
		return state
	}
	for {
		i := l.shiftOfst[state] + look
		if l.lookahead[i] != look {
			if fb := l.fallback[look]; fb != 0 {
				look = fb
				continue
			}
			j := i - look + l.c["YYWILDCARD"]
			if j < len(l.lookahead) && l.lookahead[j] == l.c["YYWILDCARD"] && look > 0 {
				return l.action[j]
			}
			return l.dflt[state]
		}
		return l.action[i]
	}
}

// findReduce is yy_find_reduce_action.
func (l *lalr) findReduce(state, goTo int) int {
	if state > l.c["YY_REDUCE_COUNT"] {
		return l.dflt[state]
	}
	i := l.reduceOfst[state] + goTo
	if i < 0 || i >= l.c["YY_ACTTAB_COUNT"] || l.lookahead[i] != goTo {
		return l.dflt[state]
	}
	return l.action[i]
}

// lalrRun is the result of running the automaton over the tokens of a statement.
type lalrRun struct {
	// rules reduced, by Lemon's number.
	rules []int
	// maxStack is the greatest number of entries on the stack above its bottom entry.
	maxStack int
	// ok is true if the automaton accepted the input; otherwise errAt is the index of the token of
	// the syntax error.
	ok    bool
	errAt int
}

// run the automaton over the tokens of the parser's trace, with the end of input after them, as
// Parse in lempar.c.
func (l *lalr) run(tokens []parser.TraceToken) lalrRun {
	var r lalrRun
	stack := []int{0}
	for i := 0; i <= len(tokens); i++ {
		look := 0 // $, the end of input
		if i < len(tokens) {
			if tokens[i].Kind == token.Illegal {
				// The parse loop reports an unrecognized token without handing it to the parser.
				r.errAt = i
				return r
			}
			look = l.code(tokens[i])
		}
		for {
			act := l.findShift(look, stack[len(stack)-1])
			switch {
			case act >= l.c["YY_MIN_REDUCE"]:
				rule := act - l.c["YY_MIN_REDUCE"]
				r.rules = append(r.rules, rule)
				size := l.ruleNRHS[rule]
				goTo := l.findReduce(stack[len(stack)-1+size], l.ruleLHS[rule])
				stack = append(stack[:len(stack)+size], goTo)
				r.maxStack = max(r.maxStack, len(stack)-1)
				continue
			case act <= l.c["YY_MAX_SHIFTREDUCE"]:
				if act > l.c["YY_MAX_SHIFT"] {
					act += l.c["YY_MIN_REDUCE"] - l.c["YY_MIN_SHIFTREDUCE"]
				}
				stack = append(stack, act)
				r.maxStack = max(r.maxStack, len(stack)-1)
			case act == l.c["YY_ACCEPT_ACTION"]:
				r.ok = true
				return r
			default:
				r.errAt = i
				return r
			}
			break
		}
	}
	r.errAt = len(tokens)
	return r
}

// code of a token of the trace, by the name of its kind.
func (l *lalr) code(t parser.TraceToken) int {
	if t.Kind == parser.TraceEOF {
		return 0
	}
	n, ok := l.tk[t.Kind.String()]
	if !ok {
		panic("no token code for " + t.Kind.String())
	}
	return n
}

// shadow runs the automaton over the first statement of src as the parser reads it, and checks
// that the two agree: on whether the grammar accepts the statement, on the token of a syntax error,
// and that the depth of the parser never exceeds the depth of the automaton's stack. It returns the
// run, or false if the text has no statement or hit a limit of the parser.
func shadow(t testing.TB, l *lalr, src string) (lalrRun, bool) {
	t.Helper()
	tr := parser.TraceParse(src)
	if len(tr.Tokens) == 0 || (tr.OK && tr.Tokens[len(tr.Tokens)-1].Kind.String() != "SEMI") {
		return lalrRun{}, false
	}
	if _, _, err := parser.Parse(src); err != nil {
		var e *parser.Error
		if errors.As(err, &e) && e.Limit {
			return lalrRun{}, false
		}
	}
	r := l.run(tr.Tokens)
	switch {
	case tr.OK && !r.ok:
		t.Errorf("%q: the parser accepts it, the automaton fails at token %v", src, r.errAt)
	case !tr.OK && r.ok:
		t.Errorf("%q: the parser fails at token %v, the automaton accepts it", src, tr.ErrAt)
	case !tr.OK && r.errAt != tr.ErrAt:
		t.Errorf("%q: the parser fails at token %v, the automaton at %v", src, tr.ErrAt, r.errAt)
	}
	if tr.MaxDepth > r.maxStack {
		t.Errorf("%q: the parser's depth %v is greater than the depth %v of the automaton's stack", src, tr.MaxDepth, r.maxStack)
	}
	return r, true
}

// TestRuleCoverage runs SQLite's own automaton beside the parser over the corpus and over sentences
// of the generator, and reports which rules of parse.y the statements that parse reduce.
func TestRuleCoverage(t *testing.T) {
	l := loadLALR(t)
	names := lemonRules(t)
	count := make([]int, len(names))
	byCorpus := make([]int, len(names))
	statements := 0
	add := func(sqls []string, counts ...[]int) {
		for _, sql := range sqls {
			r, ok := shadow(t, l, sql)
			if !ok || !r.ok {
				continue
			}
			statements++
			for _, rule := range r.rules {
				for _, c := range counts {
					c[rule]++
				}
			}
		}
	}
	corpus := corpusSQL(t)
	if slow() {
		corpus = every(corpus, 10)
	}
	add(corpus, count, byCorpus)

	// Sentences of the generator, with the rules of their derivations. Lemon folds a rule A ::= B
	// without code into the goto on B, so its automaton never reduces such a rule; for those, the
	// derivation of a sentence that parses shows that the rule was used.
	g := readGrammar(t)
	lemonIndex := map[string]int{}
	for i, name := range names {
		lemonIndex[name] = i
	}
	derived := make([]int, len(names))
	gen := newGenerator(g, 1)
	n := 20000
	if slow() {
		n /= 10
	}
	for range n {
		sql := gen.sentence("input", 4+gen.r.IntN(100))
		r, ok := shadow(t, l, sql)
		if !ok || !r.ok {
			continue
		}
		statements++
		for _, rule := range r.rules {
			count[rule]++
		}
		for _, rule := range gen.used {
			derived[lemonIndex[g.rules[rule].String()]]++
		}
	}

	covered, coveredByCorpus, folded := 0, 0, 0
	for i := range names {
		switch {
		case count[i] > 0:
			covered++
		case derived[i] > 0:
			folded++
		case !slow():
			// The sample of a slow run is too small to use every rule.
			t.Errorf("rule (%v) %v is used by no statement that parses", i, names[i])
		}
		if byCorpus[i] > 0 {
			coveredByCorpus++
		}
	}
	t.Logf("%v statements parse; SQLite's automaton reduces %v of %v rules for the corpus, and %v with the generator; "+
		"the other %v are folded into gotos and used in derivations of the generator", statements, coveredByCorpus,
		len(names), covered, folded)
	for i, name := range names {
		switch {
		case count[i] == 0:
			t.Logf("folded: (%v) %v, in %v derivations", i, name, derived[i])
		case byCorpus[i] == 0:
			t.Logf("reduced for the generator only: (%v) %v, %v times", i, name, count[i])
		}
	}
}
